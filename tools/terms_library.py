#!/usr/bin/env python3
"""Build the terms library from the cache that tools/terms_census.py fills.

terms/library.yml   one entry per distinct canonical paragraph: its hash, how many sites carry it, auto-detected risk flags
                    and a human verdict. It stores NO site text, only a short canonical prefix to recognise the paragraph.
terms/canonicalization-fixtures.json   input/expected pairs that the Python and Swift canonicalizers both test.
.terms-review/      (git-ignored) one text sheet per cluster with the full paragraphs, for the person who reviews them.

A paragraph starts as `reviewed: false`. Nothing is ever accepted on a user's behalf for a paragraph until a person has read
it and set `reviewed: true` and `verdict: ok`. Re-running keeps existing verdicts.

  python3 tools/terms_library.py [--cache .terms-cache] [--out terms/library.yml]
"""
import argparse, collections, datetime, glob, json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import terms_canon as T

FLAGS = {
    "automation": r"automat|robot|scrap|crawl|spider|\bbots?\b|data.?mining|harvest|software to access",
    "payment": r"\$\s?\d|\bfees?\b|\bcharge|billing|subscription|renew|credit card|payment|refund",
    "arbitration": r"arbitrat|class.?action|waive.{0,40}jury|jury trial",
    "permissible_use": r"fcra|permissible purpose|consumer report|employment|tenant|insurance|eligibility|credit",
    "restricted_people": r"minor|under 18|public official|celebrit|law enforcement|stalk|harass",
    "indemnity": r"indemnif|hold harmless",
    "data_sharing": r"third.?part(y|ies)|affiliates|advertis|sell|share (your|personal)",
}
HIGH_RISK = {"automation", "payment", "arbitration", "indemnity"}


def flags_for(canon):
    return sorted(k for k, rx in FLAGS.items() if re.search(rx, canon))


def load_existing(path):
    """Keep human decisions across regenerations."""
    keep = {}
    if os.path.exists(path):
        cur = None
        for line in open(path):
            m = re.match(r"  - hash: (\w+)", line)
            if m: cur = m.group(1); keep[cur] = {}
            elif cur and (m := re.match(r"    (reviewed|verdict|reviewer|note): (.*)", line)): keep[cur][m.group(1)] = m.group(2).strip()
    return keep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=".terms-cache"); ap.add_argument("--out", default="terms/library.yml")
    ap.add_argument("--review-dir", default=".terms-review")
    a = ap.parse_args()
    paras = {}                      # hash -> {"canon": ..., "sites": set, "kinds": set}
    for d in sorted(os.listdir(a.cache)):
        for f in glob.glob(f"{a.cache}/{d}/*.txt"):
            t = open(f).read()
            kind = "prompt" if os.path.basename(f).startswith("prompt") else ("privacy" if "privacy" in t.split("\n", 1)[0].lower() else "terms")
            body = t.split("\n", 1)[1] if t.startswith("URL:") else t
            for p in T.substantial(body):
                c = T.canonical(p, d); h = T.paragraph_hash(c)
                e = paras.setdefault(h, {"canon": c, "sites": set(), "kinds": set()})
                e["sites"].add(d); e["kinds"].add(kind)
    keep = load_existing(a.out)
    ordered = sorted(paras.items(), key=lambda kv: (-len(kv[1]["sites"]), kv[0]))
    lines = ["# GENERATED by tools/terms_library.py. Holds hashes, never site text. A person sets `reviewed` and `verdict`.",
             f"version: {int(datetime.date.today().strftime('%Y%m%d'))}",
             f"generated: \"{datetime.date.today().isoformat()}\"", "paragraphs:"]
    os.makedirs(a.review_dir, exist_ok=True)
    sheet = open(os.path.join(a.review_dir, "review-sheet.txt"), "w")
    for h, e in ordered:
        prev = keep.get(h, {})
        fl = flags_for(e["canon"])
        prefix = " ".join(e["canon"].split()[:8])
        lines += [f"  - hash: {h}", f"    sites: {len(e['sites'])}", f"    kinds: [{', '.join(sorted(e['kinds']))}]",
                  f"    flags: [{', '.join(fl)}]", f"    prefix: {json.dumps(prefix)}",
                  f"    reviewed: {prev.get('reviewed', 'false')}", f"    verdict: {prev.get('verdict', 'null')}"]
        sheet.write(f"[{h}] sites={len(e['sites'])} kinds={sorted(e['kinds'])} flags={fl}\n{e['canon']}\n\n")
    sheet.close()
    open(a.out, "w").write("\n".join(lines) + "\n")
    # fixtures: tricky inputs and what both canonicalizers must produce
    cases = [
        ("alabamaarrests.org", "Welcome to Alabama Arrests (www.alabamaarrests.org). Copyright ©2011-2026 alabamaarrests.org. All rights reserved."),
        ("ctarrests.org", "CT Arrests lists records in Connecticut. Visit ctarrests.org/terms — it’s our “terms”."),
        ("texascourtrecords.us", "TexasCourtRecords.us is not a consumer reporting agency. Texas Court Records may be incomplete."),
        ("usrecords.net", "By clicking \"I Agree\" you consent to our Terms (c) 2025.   Extra   spaces\n\nand lines."),
        ("example.com", "New York and North Carolina and Oregon are states; in 1989 and 2040 are not years we replace."),
    ]
    fx = [{"domain": d, "input": i, "canonical": T.canonical(i, d), "hash": T.paragraph_hash(T.canonical(i, d))} for d, i in cases]
    json.dump(fx, open("terms/canonicalization-fixtures.json", "w"), indent=2, ensure_ascii=False)
    hi = sum(1 for _, e in ordered if set(flags_for(e["canon"])) & HIGH_RISK)
    print(f"{len(ordered)} distinct paragraphs; {hi} carry a high-risk flag (automation, payment, arbitration, indemnity); library -> {a.out}")


if __name__ == "__main__":
    main()
