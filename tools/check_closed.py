#!/usr/bin/env python3
"""Finds sites that no longer respond and records the evidence in the directory as a `closed:` block, plus CLOSED_SITES.md.

Only sites with no opt-out form, page or email are tested. A site counts as closed only when every address (bare and www) fails the
same way on two tries a few seconds apart: the name does not resolve, the connection is refused or times out, the server answers 5xx,
or the host reports the name points nowhere (Cloudflare error 1000). A bot wall (403 with a security check) is NOT closed.
Usage: check_closed.py [--dir directory] [--date YYYY-MM-DD] [--dry-run]
"""
import argparse, asyncio, datetime, glob, os, re, socket, subprocess
from playwright.async_api import async_playwright

UA = "Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1"


def public_dns(host):
    """What a public resolver (Google 8.8.8.8) says, so the evidence does not depend on this machine's own DNS."""
    try:
        out = subprocess.run(["dig", "@8.8.8.8", host, "A"], capture_output=True, text=True, timeout=15).stdout
        status = (re.search(r"status: (\w+)", out) or [0, "?"])[1]; ips = re.findall(r"\sIN\s+A\s+([\d.]+)", out)
        return f"8.8.8.8 says {status}, " + (f"address {ips[0]}" if ips else "no address")
    except Exception: return "8.8.8.8 not asked"


def dns(host):
    try: return "resolves to " + sorted({a[4][0] for a in socket.getaddrinfo(host, 443, proto=socket.IPPROTO_TCP)})[0]
    except socket.gaierror as e: return f"DNS lookup failed ({e.strerror or e}); {public_dns(host)}"


async def probe(ctx, host):
    page = await ctx.new_page()
    try:
        r = await page.goto("https://" + host, wait_until="domcontentloaded", timeout=25000); await page.wait_for_timeout(1500)
        text = (await page.evaluate("document.body ? document.body.innerText : ''"))[:400].replace("\n", " ")
        status = r.status if r else 0
        if "DNS points to prohibited IP" in text or "error code: 1000" in text.lower(): return "dead", f"HTTP {status}: host reports the name points to a prohibited address (Cloudflare error 1000)"
        if status >= 500: return "dead", f"HTTP {status} server error: {text[:80]}"
        return "alive", f"HTTP {status}"
    except Exception as e:
        m = re.search(r"net::(ERR_[A-Z_]+)", str(e)); code = m.group(1) if m else re.sub(r"\s+", " ", str(e).split("Call log")[0])[:60].strip()
        return ("dead" if code in ("ERR_NAME_NOT_RESOLVED", "ERR_CONNECTION_REFUSED", "ERR_CONNECTION_TIMED_OUT", "ERR_TIMED_OUT", "ERR_CONNECTION_RESET", "ERR_ADDRESS_UNREACHABLE", "ERR_SSL_PROTOCOL_ERROR") or "Timeout" in code else "alive"), code
    finally: await page.close()


async def check(browser, domain):
    ctx = await browser.new_context(user_agent=UA); lines = []
    try:
        for attempt in (1, 2):
            verdicts = []
            for host in (domain, "www." + domain):
                v, why = await probe(ctx, host); verdicts.append(v); lines.append(re.sub(r"\s+", " ", f"try {attempt} https://{host}: {why}; {dns(host)}"))
            if "alive" in verdicts: return domain, False, lines
            if attempt == 1: await asyncio.sleep(8)
        return domain, True, lines
    finally: await ctx.close()


async def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--dir", default="directory"); ap.add_argument("--date", default=datetime.date.today().isoformat()); ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(); targets = {}
    for f in sorted(glob.glob(os.path.join(a.dir, "*.yml"))):
        s = open(f).read()
        if re.search(r"^opt_out_form:|^  found: true|^contact_email:|^opt_out_url: \"", s, re.M): continue
        targets[re.search(r'^domain: "([^"]+)"', s, re.M).group(1)] = f
    sem = asyncio.Semaphore(6)
    async with async_playwright() as p:
        browser = await p.chromium.launch()
        async def run(d):
            async with sem: return await check(browser, d)
        results = await asyncio.gather(*[run(d) for d in targets]); await browser.close()
    closed = [(d, l) for d, c, l in results if c]
    print(f"{len(closed)} of {len(targets)} sites do not respond")
    if a.dry_run: return
    for d, lines in closed:
        f = targets[d]; s = re.sub(r"\nclosed:\n(?:[ \t]+.*\n?)*", "\n", open(f).read()).rstrip("\n")
        ev = "".join(f'    - "{x.replace(chr(34), chr(39))}"\n' for x in lines)
        open(f, "w").write(s + f'\nclosed:\n  checked: "{a.date}"\n  evidence:\n{ev}')
    with open("CLOSED_SITES.md", "w") as out:
        out.write(f"# Sites that no longer respond\n\nGenerated by `tools/check_closed.py` on {a.date}. A site is listed only when both its bare and `www.` address\nfailed the same way on two tries, so a bot wall or a slow day does not count. Re-run the tool to refresh; the same evidence is in each\nsite's `directory/*.yml` under `closed:` and shows in the app's Sites tab.\n\n")
        for d, lines in sorted(closed):
            out.write(f"## {d}\n\n" + "".join(f"- {x}\n" for x in lines) + "\n")


if __name__ == "__main__":
    asyncio.run(main())
