"""tools/yamlio.py: every tool reads and writes the repository's YAML through it, in the style of .yamllint.yml."""
import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import yamlio  # noqa: E402


class YamlIO(unittest.TestCase):
    def test_values_are_single_quoted_and_mappings_are_blocks(self):
        text = yamlio.dumps({"domain": "x.example", "about": {"category": "adtech", "tracks": ["a", "b"]}, "priority": 47, "found": True, "page": None})
        self.assertEqual(text, "domain: 'x.example'\nabout:\n  category: 'adtech'\n  tracks: ['a', 'b']\npriority: 47\nfound: true\npage: null\n")

    def test_a_hash_or_a_word_yaml_1_1_reads_as_something_else_stays_text(self):
        """An unquoted 4783098342e69647 reads as a number (it was written so once, and read back as infinity); Norway's `no` as false."""
        doc = yamlio.loads(yamlio.dumps({"hash": "4783098342e69647", "code": "NO", "pages": {"no": "https://x.example/no/", "en": "https://x.example/"}}))
        self.assertEqual(doc["hash"], "4783098342e69647")
        self.assertEqual(doc["code"], "NO")
        self.assertIn("'no': ", yamlio.dumps(doc), "a key YAML 1.1 reads as false is quoted")
        self.assertEqual(list(doc["pages"]), ["no", "en"])

    def test_comments_and_order_are_kept_and_an_unchanged_file_is_not_written(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "x_example.yml")
            with open(p, "w") as f:
                f.write("# GENERATED by a tool.\nid: 'x_example'\ndomain: 'x.example'  # its own comment\nnote: 'kept'\n")
            self.assertFalse(yamlio.save(p, yamlio.load(p)), "nothing changed, nothing written")
            doc = yamlio.load(p); doc["about"] = {"category": "other"}
            self.assertTrue(yamlio.save(p, doc))
            text = open(p).read()
            self.assertTrue(text.startswith("# GENERATED by a tool.\nid: 'x_example'\ndomain: 'x.example'  # its own comment\nnote: 'kept'\nabout:\n"))

    def test_an_inline_json_mapping_from_an_older_file_becomes_a_block_with_plain_keys(self):
        doc = yamlio.loads('about: {"category": "adtech", "sells_to": []}\n')
        self.assertEqual(yamlio.dumps(doc), "about:\n  category: 'adtech'\n  sells_to: []\n")

    def test_entry_paths_and_found(self):
        self.assertEqual(yamlio.entry_path("directory", "Example.co.uk"), os.path.join("directory", "example_co_uk.yml"))
        self.assertTrue(yamlio.any_found({"live_form": {"found": True}}))
        self.assertFalse(yamlio.any_found({"live_form": {"found": False}, "domain": "x"}))


if __name__ == "__main__":
    unittest.main()
